package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

// Enum values are scoped by their type name, so adding another schema lookup
// cannot rename an existing constant through an unrelated global collision.
func generateEnums(source sourceFile) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by PGN generator; DO NOT EDIT.")
	fmt.Fprintf(&b, "// Source schema %s version %s.\n\npackage pgn\n\nimport \"fmt\"\n\n", source.SchemaVersion, source.Version)
	for _, enumeration := range source.LookupEnumerations {
		writeEnumeration(&b, enumeration, enumeration.EnumValues, false, false)
	}
	for _, enumeration := range source.LookupBitEnumerations {
		writeEnumeration(&b, enumeration, enumeration.EnumBitValues, true, false)
	}
	for _, enumeration := range source.LookupIndirectEnumerations {
		writeEnumeration(&b, enumeration, enumeration.EnumValues, false, true)
	}
	for _, enumeration := range source.LookupFieldTypeEnumerations {
		writeEnumeration(&b, enumeration, enumeration.EnumFieldTypeValues, false, false)
	}
	return format.Source(b.Bytes())
}

func enumTypeBase(name string) string {
	var b strings.Builder
	for _, part := range strings.Split(name, "_") {
		if part != "" {
			b.WriteString(strings.ToUpper(part[:1]) + strings.ToLower(part[1:]))
		}
	}
	return b.String()
}

func writeEnumeration(b *bytes.Buffer, enumeration sourceEnumeration, values []sourceEnumValue, bits, indirect bool) {
	base := enumTypeBase(enumeration.Name)
	typeName := base + "Const"
	maxValue := enumeration.MaxValue
	if bits {
		maxValue = (uint64(1) << (maxValue + 1)) - 1
	}
	if indirect {
		maxValue = 0xffff
	}
	goType := "uint64"
	for _, candidate := range []struct {
		name string
		max  uint64
	}{{"uint8", 255}, {"uint16", 65535}, {"uint32", 4294967295}} {
		if maxValue <= candidate.max {
			goType = candidate.name
			break
		}
	}
	fmt.Fprintf(b, "type %s %s\n\nconst (\n", typeName, goType)
	names := make(map[string]int)
	for _, value := range values {
		raw := enumValue(value, bits, indirect)
		name := base + strings.TrimPrefix(exportedGoIdentifier(value.Name), "Pgn")
		if indirect {
			name = fmt.Sprintf("%sClass%d", name, value.Value1)
		}
		count := names[name]
		names[name]++
		if count > 0 {
			name = fmt.Sprintf("%sValue%d", name, raw)
		}
		fmt.Fprintf(b, "%s %s = %d\n", name, typeName, raw)
	}
	fmt.Fprintln(b, ")")
	fmt.Fprintf(b, "func (e %s) GoString() string { return e.String() }\n", typeName)
	fmt.Fprintf(b, "func (e %s) String() string { switch e {\n", typeName)
	seen := make(map[uint64]bool)
	for _, value := range values {
		raw := enumValue(value, bits, indirect)
		if !seen[raw] {
			fmt.Fprintf(b, "case %d: return %q\n", raw, value.Name)
			seen[raw] = true
		}
	}
	fmt.Fprintf(b, "default: return fmt.Sprintf(%q, uint64(e))\n} }\n\n", typeName+"(%d)")
}

func enumValue(value sourceEnumValue, bits, indirect bool) uint64 {
	if bits {
		return uint64(1) << value.Bit
	}
	if indirect {
		return value.Value1<<8 | value.Value2
	}
	return value.Value
}
